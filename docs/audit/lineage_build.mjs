// Builds docs/UI_ACTION_DATA_LINEAGE.{md,csv} from lineage_actions.mjs +
// lineage_endpoints.mjs, and PROVES coverage against ui_inventory.json:
// every inventory element (page, line) must be covered by an action or by NODATA.
// Exit code 1 on any gap, unresolved anchor, or unknown endpoint key.
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
const ROOT = new URL('../../', import.meta.url);
execSync('node ' + new URL('ui_inventory.mjs', import.meta.url).pathname);
const INV = JSON.parse(readFileSync(new URL('ui_inventory.json', import.meta.url), 'utf8'));
const { ACTIONS, NODATA } = await import('./lineage_actions.mjs');
const { EP, COMMON } = await import('./lineage_endpoints.mjs');
const worker = readFileSync(new URL('worker.js', ROOT), 'utf8');
const commit = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
let errors = [];
// anchors → live worker.js lines
for (const [k, e] of Object.entries(EP)) {
  const n = worker.split(e.anchor).length - 1;
  if (n < 1) errors.push('anchor not found: ' + k);
  e.line = n >= 1 ? worker.slice(0, worker.indexOf(e.anchor)).split('\n').length : '?';
}
for (const a of ACTIONS) for (const c of a.calls) if (!EP[c]) errors.push(a.id + ': unknown endpoint ' + c);
// coverage
const covered = {};
const mark = (pg, ln, who) => { (covered[pg] ||= {}); (covered[pg][ln] ||= []).push(who); };
ACTIONS.forEach(a => a.lines.forEach(l => mark(a.page, l, a.id)));
NODATA.forEach(([pg, ls, why]) => ls.forEach(l => mark(pg, l, 'NODATA')));
const counts = {}, gaps = [];
for (const [pg, p] of Object.entries(INV)) {
  const c = counts[pg] = { elements: p.actions.length, buttons: 0, bindings: 0, timers: 0, listeners: 0 };
  for (const x of p.actions) {
    if (x.kind === 'button') c.buttons++; else if (x.kind.startsWith('timer')) c.timers++; else if (x.kind.startsWith('listener')) c.listeners++; else c.bindings++;
    if (!(covered[pg] && covered[pg][x.line])) gaps.push(pg + ':' + x.line + ' ' + x.kind + ' ' + (x.id || x.label).slice(0, 40));
  }
}
// stale mapping: a mapped line that the inventory does not contain
for (const [pg, ls] of Object.entries(covered)) for (const l of Object.keys(ls)) {
  if (!INV[pg]) { errors.push('unknown page ' + pg); continue; }
  if (!INV[pg].actions.some(x => String(x.line) === l)) errors.push('mapped line not in inventory: ' + pg + ':' + l + ' (' + ls[l].join(',') + ')');
}
if (gaps.length) errors.push(...gaps.map(g => 'UNMAPPED ' + g));
// ---- CSV
const q = v => '"' + String(v == null ? '' : v).replace(/"/g, '""').replace(/\s+/g, ' ') + '"';
const cols = ['ID', 'Page', 'Screen', 'Action', 'UI Label', 'Frontend File', 'Lines', 'Handler', 'Endpoint', 'Backend Handler', 'Primary Source', 'Secondary Source', 'Table',
  'SQL/API', 'Live/Stored/Mixed', 'Range Logic', 'Merge Logic', 'Dedup Rule', 'Canonical Filter', 'Output', 'Side Effects', 'D1 Reads', 'KV Ops', 'Provider Calls', 'Reuses Browser State', 'Differs From Other Actions', 'Same As Trader', 'Notes'];
const rows = [cols.map(q).join(',')];
for (const a of ACTIONS) {
  const eps = a.calls.map(k => EP[k]);
  const j = f => eps.map(e => e[f]).filter(Boolean).join(' || ');
  rows.push([a.id, a.screen, a.screen, a.kind, a.label, a.page, a.lines.join(' '), a.handler, a.params, eps.map(e => e.route + ' @worker.js:' + e.line).join(' || '),
    a.source, j('fallback'), j('table'), j('sql'), eps.length ? [...new Set(eps.map(e => e.mixed))].join(' + ') : a.source, a.range, j('merge'), j('dedup'), j('filter'),
    a.output, [a.side, j('side')].filter(Boolean).join(' | '), j('d1') || '0', j('kv') || '0', j('provider') || '0', a.reuse, a.differs, a.trader,
    [a.notes, a.trigger ? 'TRIGGER: ' + a.trigger : '', a.import ? 'IMPORT: ' + JSON.stringify(a.import) : ''].filter(Boolean).join(' | ')].map(q).join(','));
}
writeFileSync(new URL('UI_ACTION_DATA_LINEAGE.csv', new URL('../', import.meta.url)), rows.join('\n') + '\n');
// ---- Markdown
const md = [];
const P = s => md.push(s);
P('# UI ACTION → DATA LINEAGE');
P('');
P(`Generated by \`docs/audit/lineage_build.mjs\` at commit \`${commit}\` from \`lineage_actions.mjs\` (frontend) and \`lineage_endpoints.mjs\` (backend). ` +
  'Line numbers are resolved at build time from the source, so they match this commit. Evidence is CODE-DERIVED unless a record says LOCALLY VERIFIED or NOT VERIFIED.');
P('');
P('Source codes: **D1** (bars-vault) · **SUPABASE** (archive_bars) · **LIVE_PROVIDER** (Yahoo 1-min, Yahoo daily, Cboe book, frankfurter.app) · **KV_SNAPSHOT** · **GITHUB_ARCHIVE** · **BROWSER_MEMORY** (page variables, localStorage) · **MIXED**.');
P('');
P('Retention (CODE-DERIVED): D1 keeps 60 trading days (`D1_KEEP_DAYS`), Supabase 42 (`ARCHIVE_DAYS`, pruned nightly), GitHub CSVs are rebuilt from Supabase with the last 42 dates. Nothing the app reads holds data older than ~60 trading days.');
P('');
P('## 1. Master table');
P('');
P('| ID | Screen | Button / action | What it does | Where the data comes from | What you get |');
P('|---|---|---|---|---|---|');
for (const a of ACTIONS) P(`| [${a.id}](#${a.id.toLowerCase()}) | ${a.screen} | ${a.label} | ${a.handler.replace(/\|/g, '/')} | ${a.source.replace(/\|/g, '/').split('. ')[0]} | ${a.output.replace(/\|/g, '/')} |`);
P('');
P('## 2. "One week of 1-minute candles for AAPL" — proven path');
P('');
P('Single-symbol week: **/bars → הורדה מרובה**, symbol AAPL, from/to = the week, **⬇ הורד** (B-10), or **הורד כל ההיסטוריה של הסימבול** (B-06, full range). Both call `' + EP.bars_export.route + '` (worker.js:' + EP.bars_export.line + ').');
P('');
P('1. D1: `' + EP.bars_export.sql.split(' ; ')[0] + '`');
P('2. Supabase, same range: `' + EP.bars_export.sql.split(' ; ')[1].replace(/^then /, '') + '`');
P('3. Merge: ' + EP.bars_export.merge + ' Dedup: ' + EP.bars_export.dedup + '.');
P('4. Yahoo: never. GitHub: never. KV: never.');
P('5. Failure mode: ' + EP.bars_export.fallback + '.');
P('');
P('| DATE (example week) | SOURCE | WHY |');
P('|---|---|---|');
P('| any date within the last 60 trading days, AAPL tracked | D1, plus any minute only Supabase holds | union; D1 row wins when both have the minute |');
P('| a date before AAPL was added to the tracked set (D1 never collected it; the nightly universe pass archived it) | Supabase only | D1 has no rows for that date |');
P('| a date D1 has pruned but Supabase still holds | does not occur with the current constants (Supabase keeps 42 trading days, D1 60) | — |');
P('| any date, symbol not tracked (universe only) | Supabase | D1 never held it |');
P('| older than ~60 trading days | nowhere — the CSV has no rows for that date | both stores pruned |');
P('| any date, Supabase request fails | D1 only, silently | error swallowed in the route |');
P('');
P('Other "history" buttons do NOT behave the same: S-07/S-08 (scan) and D-03 (data page) use `/export`, which returns D1 only whenever D1 holds any row of the symbol; R-11/T-11 (radar range copy) read one `/day` per date, which never unions stores inside a day.');
P('');
P('## 3. Detailed records');
for (const a of ACTIONS) {
  P('');
  P(`### ${a.id}`);
  P('');
  P(`**${a.label}** — ${a.screen} · \`${a.page}\` lines ${a.lines.length ? a.lines.join(', ') : '(top-level startup code)'} · kind ${a.kind}`);
  P('');
  P('| Field | Value |');
  P('|---|---|');
  const row = (k, v) => v != null && v !== '' && P(`| ${k} | ${String(v).replace(/\|/g, '/').replace(/\n/g, ' ')} |`);
  row('Handler / functions', a.handler); row('Trigger', a.trigger); row('Request(s) sent', a.params || '—'); row('Range / symbols', a.range);
  row('Reuses browser state', a.reuse); row('Final source', a.source); row('Output to the user', a.output); row('Side effects', a.side);
  row('Can differ from another action', a.differs); row('Same source as Trader', a.trader); row('Notes', a.notes);
  if (a.calls.length) row('Backend', a.calls.map(k => `[${EP[k].route}](#ep-${k.replace(/_/g, '-')}) (worker.js:${EP[k].line})`).join('<br>'));
  if (a.fields) { P(''); P('Field-by-field provenance:'); P(''); P('| Field | Source |'); P('|---|---|'); a.fields.forEach(([f, s]) => P(`| ${f} | ${s.replace(/\|/g, '/')} |`)); }
  if (a.import && typeof a.import === 'object') { P(''); P('Import path:'); P(''); P('| Step | Behaviour |'); P('|---|---|'); Object.entries(a.import).forEach(([k, v]) => P(`| ${k} | ${String(v).replace(/\|/g, '/')} |`)); }
}
P('');
P('## 4. Backend endpoint records');
P('');
P('Common to every request: ' + COMMON + '.');
for (const [k, e] of Object.entries(EP)) {
  P('');
  P(`### ep-${k.replace(/_/g, '-')}`);
  P('');
  P(`\`${e.route}\` — worker.js:${e.line} — **${e.mixed}**`);
  P('');
  P('| Field | Value |'); P('|---|---|');
  for (const f of ['source', 'table', 'sql', 'fallback', 'merge', 'dedup', 'filter', 'tz', 'live', 'output', 'side', 'd1', 'kv', 'provider'])
    if (e[f]) P(`| ${f} | ${String(e[f]).replace(/\|/g, '/')} |`);
}
P('');
P('## 5. Elements with no data interaction');
P('');
P('| Page | Lines | What it is |'); P('|---|---|---|');
NODATA.forEach(([pg, ls, why]) => P(`| ${pg} | ${ls.join(', ')} | ${why} |`));
P('');
P('## 6. Coverage check');
P('');
P('Inventory: `docs/audit/ui_inventory.mjs` (buttons in HTML and in JS strings, inline handlers, `.onX=` bindings, `on(\'#id\',…)` helper bindings, `addEventListener`, `setInterval`/`setTimeout`). The builder fails if any inventory element is unmapped.');
P('');
P('| Page | Elements | Buttons | Bindings | Listeners | Timers |'); P('|---|---|---|---|---|---|');
const tot = { elements: 0, buttons: 0, bindings: 0, timers: 0, listeners: 0 };
for (const [pg, c] of Object.entries(counts)) { P(`| ${pg} | ${c.elements} | ${c.buttons} | ${c.bindings} | ${c.listeners} | ${c.timers} |`); for (const k in tot) tot[k] += c[k]; }
P(`| **total (${Object.keys(counts).length} served pages)** | **${tot.elements}** | **${tot.buttons}** | **${tot.bindings}** | **${tot.listeners}** | **${tot.timers}** |`);
const byKind = k => ACTIONS.filter(a => a.kind === k).length;
P('');
P(`Actions documented: ${ACTIONS.length} (LOAD ${byKind('LOAD')}, AUTO ${byKind('AUTO')}, CLICK ${byKind('CLICK')}, CHANGE ${byKind('CHANGE')}, COPY ${byKind('COPY')}, DOWNLOAD ${byKind('DOWNLOAD')}, IMPORT ${byKind('IMPORT')}). No-data groups: ${NODATA.length}.`);
P(`Unmapped inventory elements: **${gaps.length}**. Other build errors: **${errors.length - gaps.length}**.`);
P('');
P('Not served by any route and containing no network code (checked by grep for fetch/XMLHttpRequest/endpoint strings): qa-team-report.html, trader-v2-qa-holdout.html, trader-v2-qa-indep.html, trader-v2-qa-report.html, trader-v2-v188-90symbol-validation.html, trader-v2-v190-corrected-baseline.html.');
P('');
P('Limits of this proof: the inventory is static. An element created and bound in a way none of its patterns match would be missed; every `fetch`/`j(` site in every page was separately listed and each is attributed to an action above.');
writeFileSync(new URL('UI_ACTION_DATA_LINEAGE.md', new URL('../', import.meta.url)), md.join('\n') + '\n');
console.log('actions', ACTIONS.length, '| inventory elements', tot.elements, '| unmapped', gaps.length, '| errors', errors.length);
errors.forEach(e => console.log('  ' + e));
process.exit(errors.length ? 1 : 0);
